export function generateSeedLeads(): Lead[] {
  return INITIAL_LEADS_RAW.map((raw, idx) => {
    const scored = computeLeadScore(raw);
    const id = `lead_${(idx + 1).toString().padStart(3, '0')}`;
    
    // Explicitly set review queue decision for items that need review
    let reviewDecision: Lead['review_decision'] = 'Pending';
    if (scored.status === 'Qualified') {
      reviewDecision = 'Approved';
    } else if (scored.status === 'Disqualified') {
      reviewDecision = 'Rejected';
    }

    return {
      id,
      ...raw,
      score: scored.score,
      priority: scored.priority,
      status: scored.status,
      review_decision: reviewDecision,
      review_notes: scored.needsReviewReason,
      explanation: scored.explanation,
      feature_importance: scored.feature_importance,
      updated_at: raw.created_at,
    };
  });
}
